# ─────────────────────────────────────────────────────────────────────────────
# STEP 1 — Load and filter the COCO CSV
# ─────────────────────────────────────────────────────────────────────────────

def load_filtered_csv(csv_path: Path) -> pd.DataFrame:
    """
    Load coco_processed.csv and return only rows whose category_name
    is in TARGET_CLASSES.

    Returns a DataFrame with columns:
        image_id, image_path, width, height,
        ann_id, bbox_x, bbox_y, bbox_width, bbox_height,
        category_name
    """
    print(f"\n[1/6] Loading CSV: {csv_path}")
    if not csv_path.exists():
        sys.exit(
            f"[ERROR] CSV not found at {csv_path}\n"
            "Run Notebook 02 first to generate coco_processed.csv."
        )

    usecols = [
        "image_id", "image_path", "width", "height",
        "ann_id", "bbox_x", "bbox_y", "bbox_width", "bbox_height",
        "category_name",
    ]
    df = pd.read_csv(csv_path, usecols=usecols)
    total_rows = len(df)
    print(f"    Loaded {total_rows:,} total annotations.")

    # Filter to 15 classes
    df = df[df["category_name"].isin(TARGET_CLASSES)].copy()
    print(f"    Kept {len(df):,} annotations across {df['image_id'].nunique():,} "
          f"images for the 15 target classes.")

    # Show per-class counts for transparency
    print("\n    Per-class annotation counts:")
    class_counts = df["category_name"].value_counts()
    for cls in TARGET_CLASSES:
        print(f"      [{CLASS_TO_ID[cls]:>2d}] {cls:20s}  {class_counts.get(cls, 0):>8,}")

    return df


# ─────────────────────────────────────────────────────────────────────────────
# STEP 2 — 80/20 train/val split at the IMAGE level
# ─────────────────────────────────────────────────────────────────────────────

def split_images(df: pd.DataFrame) -> tuple[list[int], list[int]]:
    """
    Split unique image IDs into train and val sets (80/20).

    Splitting is done at the IMAGE level (not annotation level) to prevent
    the same image appearing in both splits.

    The val set is capped at MAX_VAL_IMAGES (3,000) to prevent the numpy
    MemoryError that occurs when ap_per_class allocates a (N_preds × 10)
    int64 matrix for ~11,700 val images at validation confidence=0.001.

    Returns (train_ids, val_ids) as lists of image_id integers.
    """
    print(f"\n[2/6] Creating {TRAIN_RATIO:.0%}/{1-TRAIN_RATIO:.0%} train/val split...")

    unique_image_ids = df["image_id"].unique().tolist()
    train_ids, val_ids = train_test_split(
        unique_image_ids,
        test_size=1.0 - TRAIN_RATIO,
        random_state=RANDOM_SEED,
        shuffle=True,
    )

    # Cap the val set to avoid numpy MemoryError in ap_per_class
    if len(val_ids) > MAX_VAL_IMAGES:
        original_val_count = len(val_ids)
        import random as _random
        _rng = _random.Random(RANDOM_SEED)
        val_ids = _rng.sample(val_ids, MAX_VAL_IMAGES)
        print(f"    Val capped at {MAX_VAL_IMAGES:,} images (was {original_val_count:,})")

    print(f"    Train images : {len(train_ids):,}")
    print(f"    Val images   : {len(val_ids):,}")

    # Annotation counts per split
    train_anns = df[df["image_id"].isin(train_ids)]
    val_anns   = df[df["image_id"].isin(val_ids)]
    print(f"    Train annotations : {len(train_anns):,}")
    print(f"    Val annotations   : {len(val_anns):,}")

    return train_ids, val_ids


# ─────────────────────────────────────────────────────────────────────────────
# STEP 3 — Convert bboxes to YOLO format and write label .txt files
# ─────────────────────────────────────────────────────────────────────────────

def coco_xywh_to_yolo(
    bbox_x: float, bbox_y: float, bbox_w: float, bbox_h: float,
    img_w: int, img_h: int,
) -> tuple[float, float, float, float]:
    """
    Convert COCO bbox [x_topleft, y_topleft, width, height] (pixel absolute)
    to YOLO format [cx, cy, w, h] (normalized 0–1).

    COCO format : top-left corner + width/height, pixel absolute
    YOLO format : center-x, center-y, width, height — all normalized by
                  image dimensions to the range [0.0, 1.0]
    """
    cx = (bbox_x + bbox_w / 2.0) / img_w
    cy = (bbox_y + bbox_h / 2.0) / img_h
    w  = bbox_w / img_w
    h  = bbox_h / img_h
    # Clamp to [0, 1] to handle any minor floating-point overshoot
    cx = max(0.0, min(1.0, cx))
    cy = max(0.0, min(1.0, cy))
    w  = max(0.0, min(1.0, w))
    h  = max(0.0, min(1.0, h))
    return cx, cy, w, h


def write_label_files(
    df: pd.DataFrame,
    image_ids: list[int],
    labels_dir: Path,
) -> dict[int, str]:
    """
    For each image in image_ids, write a YOLO label .txt file.

    Each line of the .txt file:
        <class_id> <cx> <cy> <width> <height>   (all space-separated, 6 d.p.)

    Images with zero valid annotations in the 15 classes (should not happen
    after filtering, but we guard anyway) are skipped.

    Returns image_id → image_filename mapping for the next step.
    """
    labels_dir.mkdir(parents=True, exist_ok=True)

    # Group annotations by image_id for O(1) lookup
    grouped = df[df["image_id"].isin(image_ids)].groupby("image_id")

    image_map: dict[int, str] = {}  # image_id → filename

    skipped = 0
    for img_id in tqdm(image_ids, desc=f"    Writing labels → {labels_dir.name}", unit="img"):
        if img_id not in grouped.groups:
            skipped += 1
            continue

        group = grouped.get_group(img_id)
        img_w  = int(group["width"].iloc[0])
        img_h  = int(group["height"].iloc[0])
        img_fn = group["image_path"].iloc[0]  # e.g. "COCO_train2014_000000481480.jpg"

        lines = []
        for _, row in group.iterrows():
            cls_id = CLASS_TO_ID[row["category_name"]]
            cx, cy, w, h = coco_xywh_to_yolo(
                row["bbox_x"], row["bbox_y"],
                row["bbox_width"], row["bbox_height"],
                img_w, img_h,
            )
            # Skip degenerate boxes (can happen after clamp if box was 0-area)
            if w <= 0 or h <= 0:
                continue
            lines.append(f"{cls_id} {cx:.6f} {cy:.6f} {w:.6f} {h:.6f}")

        if not lines:
            skipped += 1
            continue

        # Write label file — stem must match the image filename stem
        stem = Path(img_fn).stem
        label_path = labels_dir / f"{stem}.txt"
        label_path.write_text("\n".join(lines))

        image_map[img_id] = img_fn

    if skipped:
        print(f"    ⚠ Skipped {skipped} images with no valid labels.")

    return image_map


# ─────────────────────────────────────────────────────────────────────────────
# STEP 4 — Hardlink images into YOLO directory structure
# ─────────────────────────────────────────────────────────────────────────────

def link_images(
    image_map: dict[int, str],
    source_dir: Path,
    dest_dir: Path,
) -> None:
    """
    Create hardlinks (not copies) from source_dir into dest_dir.

    Hardlinks:
        • Use zero extra disk space (same file, two directory entries)
        • Work on Windows without admin rights
        • Are indistinguishable from regular files to YOLO

    Falls back to shutil.copy2() if hardlink creation fails (e.g. cross-device).
    """
    dest_dir.mkdir(parents=True, exist_ok=True)

    fallback_to_copy = False
    linked = 0
    skipped = 0

    for img_fn in tqdm(image_map.values(), desc=f"    Linking images → {dest_dir.name}", unit="img"):
        src = source_dir / img_fn
        dst = dest_dir / img_fn

        if dst.exists():
            skipped += 1
            continue

        if not src.exists():
            print(f"\n    ⚠ Image not found on disk: {src}")
            skipped += 1
            continue

        try:
            if not fallback_to_copy:
                os.link(src, dst)
            else:
                shutil.copy2(src, dst)
            linked += 1
        except OSError:
            # Cross-device or permission issue — switch to copy for remainder
            fallback_to_copy = True
            try:
                shutil.copy2(src, dst)
                linked += 1
            except Exception as exc:
                print(f"\n    ✗ Could not link/copy {img_fn}: {exc}")
                skipped += 1

    mode = "copied" if fallback_to_copy else "hardlinked"
    print(f"    {linked:,} images {mode}; {skipped:,} skipped (already existed or missing).")
    if fallback_to_copy:
        print("    ℹ Fell back to copying (cross-device links not supported).")


# ─────────────────────────────────────────────────────────────────────────────
# STEP 5 — Write dataset.yaml
# ─────────────────────────────────────────────────────────────────────────────

def write_dataset_yaml(yaml_path: Path, dataset_dir: Path) -> None:
    """
    Write the Ultralytics dataset.yaml file.

    Ultralytics requires:
        path : absolute path to the dataset root
        train: relative path to train images
        val  : relative path to val images
        nc   : number of classes
        names: list of class names (index = class_id)
    """
    yaml_content = f"""\
# dataset.yaml — Auto-generated by train.py
# DO NOT edit manually; re-run train.py to regenerate.

path: {dataset_dir.as_posix()}
train: images/train
val:   images/val

nc: {len(TARGET_CLASSES)}
names:
"""
    for i, name in enumerate(TARGET_CLASSES):
        yaml_content += f"  {i}: {name}\n"

    yaml_path.write_text(yaml_content, encoding="utf-8")
    print(f"\n[5/6] dataset.yaml written → {yaml_path}")
    print(f"      {len(TARGET_CLASSES)} classes: {', '.join(TARGET_CLASSES)}")


# ─────────────────────────────────────────────────────────────────────────────
# STEP 6 — Fine-tune YOLOv8 and evaluate
# ─────────────────────────────────────────────────────────────────────────────

def run_training(args: argparse.Namespace, yaml_path: Path) -> None:
    """
    Fine-tune the pretrained YOLOv8 model on our 15-class dataset.
    Then run validation and print mAP results.
    """
    print(f"\n[6/6] Starting YOLOv8 fine-tuning...")
    print(f"      Base model : {args.model}")
    print(f"      Epochs     : {args.epochs}")
    print(f"      Batch size : {args.batch}")
    print(f"      Image size : {args.imgsz}×{args.imgsz}")
    print(f"      Device     : {args.device}")
    print(f"      Dataset    : {yaml_path}")
    print()

    model = YOLO(args.model)

    t_start = time.perf_counter()

    results = model.train(
        data=str(yaml_path),
        epochs=args.epochs,
        batch=args.batch,
        imgsz=args.imgsz,
        device=args.device,
        workers=args.workers,
        project=str(RUNS_DIR),
        name="train",
        exist_ok=True,          # overwrite previous run with same name
        pretrained=True,        # start from COCO pretrained weights (key for fine-tune)
        amp=True,               # automatic mixed precision (halves VRAM usage)
        cache=False,            # don't cache images in RAM (not needed with hardlinks)
        optimizer="SGD",        # SGD converges well for COCO-family fine-tuning
        lr0=0.01,               # initial learning rate
        lrf=0.1,                # final lr = lr0 * lrf (cosine decay)
        momentum=0.937,
        weight_decay=0.0005,
        warmup_epochs=3.0,      # 3-epoch LR warmup
        warmup_momentum=0.8,
        # Augmentation (Ultralytics defaults — good for COCO-family data)
        hsv_h=0.015,            # hue augmentation
        hsv_s=0.7,              # saturation augmentation
        hsv_v=0.4,              # value augmentation
        degrees=0.0,            # no rotation (images are right-way-up)
        translate=0.1,
        scale=0.5,
        mosaic=1.0,             # mosaic augmentation (greatly improves small-object AP)
        mixup=0.0,              # no mixup (increases training time for marginal gain)
        copy_paste=0.0,
        # Logging / saving
        save=True,
        save_period=-1,         # only save best and last (not every epoch)
        plots=True,             # generate PR curve, confusion matrix, etc.
        verbose=True,
    )

    t_train = time.perf_counter() - t_start
    print(f"\n    Training complete in {t_train/3600:.2f} hours.")

    # ── Validation ────────────────────────────────────────────────────────────
    print("\n    Running final validation on best.pt...")
    best_weights = RUNS_DIR / "train" / "weights" / "best.pt"
    if best_weights.exists():
        best_model = YOLO(str(best_weights))
        val_results = best_model.val(
            data=str(yaml_path),
            imgsz=args.imgsz,
            device=args.device,
            verbose=True,
        )
    else:
        print("    ⚠ best.pt not found; skipping separate validation.")
        val_results = None

    # ── Save human-readable summary ───────────────────────────────────────────
    _write_summary(args, t_train, results, val_results)


def _write_summary(
    args: argparse.Namespace,
    train_time_s: float,
    train_results,
    val_results,
) -> None:
    """Write a human-readable results_summary.txt."""
    lines = [
        "=" * 65,
        "YOLO FINE-TUNING RESULTS SUMMARY",
        f"Generated: {time.strftime('%Y-%m-%d %H:%M:%S')}",
        "=" * 65,
        "",
        "TRAINING CONFIGURATION",
        "-" * 40,
        f"  Base model   : {args.model}",
        f"  Dataset      : {YAML_PATH}",
        f"  Classes      : {len(TARGET_CLASSES)}",
        f"  Epochs       : {args.epochs}",
        f"  Batch size   : {args.batch}",
        f"  Image size   : {args.imgsz}",
        f"  Device       : {args.device}",
        f"  Random seed  : {RANDOM_SEED}",
        f"  Train ratio  : {TRAIN_RATIO}",
        f"  Training time: {train_time_s/3600:.2f} hours "
          f"({train_time_s/60:.0f} minutes)",
        "",
        "TARGET CLASSES",
        "-" * 40,
    ]
    for i, cls in enumerate(TARGET_CLASSES):
        lines.append(f"  [{i:>2d}] {cls}")

    lines += ["", "VALIDATION RESULTS (best.pt)", "-" * 40]

    if val_results is not None:
        try:
            box = val_results.box
            lines += [
                f"  mAP@50       : {box.map50:.4f}  ({box.map50*100:.1f}%)",
                f"  mAP@50:95    : {box.map:.4f}   ({box.map*100:.1f}%)",
                f"  Precision    : {box.mp:.4f}",
                f"  Recall       : {box.mr:.4f}",
                "",
                "  Per-class AP@50:",
            ]
            if hasattr(box, 'ap50') and box.ap50 is not None:
                for i, cls in enumerate(TARGET_CLASSES):
                    ap = float(box.ap50[i]) if i < len(box.ap50) else float('nan')
                    lines.append(f"    [{i:>2d}] {cls:20s}  {ap:.4f}  ({ap*100:.1f}%)")
        except Exception as exc:
            lines.append(f"  (Could not parse val_results: {exc})")
    else:
        lines.append("  (Validation was not run or failed)")

    lines += [
        "",
        "OUTPUT FILES",
        "-" * 40,
        f"  Best weights    : {RUNS_DIR / 'train' / 'weights' / 'best.pt'}",
        f"  Last weights    : {RUNS_DIR / 'train' / 'weights' / 'last.pt'}",
        f"  Training curves : {RUNS_DIR / 'train' / 'results.csv'}",
        f"  Confusion matrix: {RUNS_DIR / 'train' / 'confusion_matrix.png'}",
        "",
        "NEXT STEPS",
        "-" * 40,
        "  1. Copy best.pt to module-3/",
        "  2. Update module-3/config/config.py: YOLO_MODEL_PATH = 'path/to/best.pt'",
        "  3. Run module-3: python main.py --target bottle --navigate",
        "=" * 65,
    ]

    summary_text = "\n".join(lines)
    SUMMARY_PATH.write_text(summary_text, encoding="utf-8")
    print(f"\n{summary_text}")
    print(f"\n    Summary saved → {SUMMARY_PATH}")


