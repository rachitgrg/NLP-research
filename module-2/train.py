def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "YOLOv8 fine-tuning on a 15-class indoor assistive-navigation subset.\n"
            "All parameters have sensible defaults for an RTX 3050 6GB."
        )
    )
    parser.add_argument(
        "--model", default=DEFAULT_MODEL,
        help=f"Base YOLO model/weights. Default: {DEFAULT_MODEL}. "
             "Options: yolov8n.pt, yolov8s.pt, yolov8m.pt"
    )
    parser.add_argument(
        "--epochs", type=int, default=DEFAULT_EPOCHS,
        help=f"Training epochs. Default: {DEFAULT_EPOCHS}."
    )
    parser.add_argument(
        "--batch", type=int, default=DEFAULT_BATCH,
        help=f"Batch size. Default: {DEFAULT_BATCH} (safe for 6GB VRAM). "
             "Use 16-32 on A100."
    )
    parser.add_argument(
        "--imgsz", type=int, default=DEFAULT_IMGSZ,
        help=f"Inference image size (square pixels). Default: {DEFAULT_IMGSZ}."
    )
    parser.add_argument(
        "--device", default=DEFAULT_DEVICE,
        help=f"Inference device. '0' = first GPU, 'cpu' = CPU. Default: {DEFAULT_DEVICE!r}."
    )
    parser.add_argument(
        "--workers", type=int, default=DEFAULT_WORKERS,
        help=f"DataLoader worker processes. Default: {DEFAULT_WORKERS}."
    )
    parser.add_argument(
        "--skip-dataset-prep", action="store_true",
        help="Skip label file generation and image linking (use if already done)."
    )
    parser.add_argument(
        "--rebuild-val", action="store_true",
        help=(
            "Rebuild ONLY the val split (labels + image links). "
            "Use this after changing MAX_VAL_IMAGES without re-running full prep. "
            "Train split is left untouched."
        )
    )
    parser.add_argument(
        "--resume", action="store_true",
        help=(
            "Resume interrupted training from runs/train/weights/last.pt. "
            "All hyperparameters are restored from the checkpoint automatically."
        )
    )
    parser.add_argument(
        "--safe-mode", dest="safe_mode", action="store_true",
        help=(
            "Use with --resume. Reduces batch to 4 and workers to 2 to ease "
            "GPU pressure when using the laptop simultaneously during training."
        )
    )
    return parser.parse_args()


