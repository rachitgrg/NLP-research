#!/usr/bin/env python3
# train.py
# ─────────────────────────────────────────────────────────────────────────────
# Module 2 — YOLOv8 Fine-Tuning Pipeline
#
# Purpose
# ───────
# Converts the already-cleaned coco_processed.csv into YOLO training format,
# fine-tunes YOLOv8n on a 15-class indoor assistive-navigation subset,
# evaluates on a held-out validation split, and saves a results summary.
#
# The 15 target classes
# ─────────────────────
# Obstacles   : person, chair, dining table, couch, bed
# Find targets: bottle, cup, bowl, laptop, cell phone,
#               book, tv, backpack, umbrella, suitcase
#
# Data flow
# ─────────
#   coco_processed.csv
#       → filter to 15 classes
#       → 80/20 image-level train/val split (fixed seed, reproducible)
#       → YOLO label .txt files  (cx, cy, w, h — normalized 0–1)
#       → hardlinks to original images  (no disk duplication)
#       → dataset.yaml
#       → model.train()  ← Ultralytics API
#       → model.val()
#       → results_summary.txt
#
# Usage
# ─────
#   # From inside module-2/ with ultralytics installed:
#   python train.py
#
#   # Override any param at the command line:
#   python train.py --epochs 50 --batch 16 --device cuda
#   python train.py --epochs 30 --batch 8 --imgsz 640 --device 0
#
# Dependencies
# ────────────
#   pip install ultralytics pandas scikit-learn tqdm
#
# Outputs (all inside module-2/runs/)
# ────────────────────────────────────
#   runs/detect/train/weights/best.pt      ← use THIS in Module 3
#   runs/detect/train/weights/last.pt
#   runs/detect/train/results.csv          ← per-epoch metrics
#   runs/detect/train/confusion_matrix.png
#   runs/detect/train/PR_curve.png
#   runs/detect/train/val_batch*.jpg
#   results_summary.txt                    ← human-readable summary
# ─────────────────────────────────────────────────────────────────────────────

